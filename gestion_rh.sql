CREATE TABLE DEMANDE_RECRUTEMENT (
  ID                    NUMBER(10)     NOT NULL,
  POSTE_ID              NUMBER(10)     NOT NULL,
  MANAGER_ID            NUMBER(10)     NOT NULL,
  TYPE_DEMANDE          VARCHAR2(15)   DEFAULT 'CREATION' NOT NULL,
  EMPLOYE_REMPLACE_ID   NUMBER(10),
  MOTIF                 VARCHAR2(1000) NOT NULL,
  EFFECTIF_DEMANDE      NUMBER(3)      DEFAULT 1 NOT NULL,
  BUDGET_ALLOUE         NUMBER(15,2),
  DATE_SOUHAITEE        DATE           NOT NULL,
  STATUT_VALIDATION     VARCHAR2(20)   DEFAULT 'BROUILLON' NOT NULL,
  CONSTRAINT PK_DEMANDE_RECRUTEMENT PRIMARY KEY (ID),
  CONSTRAINT FK_DR_POSTE   FOREIGN KEY (POSTE_ID)            REFERENCES POSTE (ID),
  CONSTRAINT FK_DR_MANAGER FOREIGN KEY (MANAGER_ID)          REFERENCES UTILISATEUR (ID),
  CONSTRAINT FK_DR_EMP     FOREIGN KEY (EMPLOYE_REMPLACE_ID) REFERENCES EMPLOYE (ID),
  CONSTRAINT CK_DR_TYPE    CHECK (TYPE_DEMANDE IN ('CREATION','REMPLACEMENT')),
  CONSTRAINT CK_DR_REMPL   CHECK (TYPE_DEMANDE = 'CREATION' OR EMPLOYE_REMPLACE_ID IS NOT NULL),
  CONSTRAINT CK_DR_EFF     CHECK (EFFECTIF_DEMANDE > 0),
  CONSTRAINT CK_DR_BUDGET  CHECK (BUDGET_ALLOUE IS NULL OR BUDGET_ALLOUE >= 0),
  CONSTRAINT CK_DR_STATUT  CHECK (STATUT_VALIDATION IN
      ('BROUILLON','ATTENTE_RH','ATTENTE_DIRECTION','VALIDEE','REFUSEE'))
);

-- Une ligne par decision de validation (RH puis Direction). Rien n'est ecrase.
CREATE TABLE DEMANDE_VALIDATION (
  ID             NUMBER(10)     NOT NULL,
  DEMANDE_ID     NUMBER(10)     NOT NULL,
  ETAPE          VARCHAR2(10)   NOT NULL,
  DECISION       VARCHAR2(10)   NOT NULL,
  VALIDEUR_ID    NUMBER(10)     NOT NULL,
  DATE_DECISION  TIMESTAMP(6)   DEFAULT SYSTIMESTAMP NOT NULL,
  JUSTIFICATION  VARCHAR2(1000),
  CONSTRAINT PK_DEMANDE_VALIDATION PRIMARY KEY (ID),
  CONSTRAINT FK_DV_DR  FOREIGN KEY (DEMANDE_ID)  REFERENCES DEMANDE_RECRUTEMENT (ID),
  CONSTRAINT FK_DV_VAL FOREIGN KEY (VALIDEUR_ID) REFERENCES UTILISATEUR (ID),
  CONSTRAINT CK_DV_ETAPE    CHECK (ETAPE IN ('RH','DIRECTION')),
  CONSTRAINT CK_DV_DECISION CHECK (DECISION IN ('VALIDEE','REFUSEE')),
  CONSTRAINT CK_DV_JUSTIF   CHECK (DECISION = 'VALIDEE' OR JUSTIFICATION IS NOT NULL)
);

