CREATE TABLE POSTE (
  ID              NUMBER(10)      NOT NULL,
  CODE_POSTE      VARCHAR2(30)    NOT NULL,
  INTITULE        VARCHAR2(200)   NOT NULL,
  DESCRIPTION     VARCHAR2(4000),
  DEPARTEMENT_ID  NUMBER(10)      NOT NULL,
  STATUT_POSTE    VARCHAR2(10)    DEFAULT 'CREE' NOT NULL,
  CONSTRAINT PK_POSTE PRIMARY KEY (ID),
