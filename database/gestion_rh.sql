  DATE_FIN_EFFECTIVE     DATE,
  SALAIRE_BRUT           NUMBER(15,2)   NOT NULL,
  DEVISE                 VARCHAR2(3)    DEFAULT 'EUR' NOT NULL,   -- adapter a la devise locale
  STATUT_CONTRAT         VARCHAR2(12)   DEFAULT 'EN_ATTENTE' NOT NULL,
  CONSTRAINT PK_CONTRAT PRIMARY KEY (ID),
  CONSTRAINT FK_CTR_EMP   FOREIGN KEY (EMPLOYE_ID)           REFERENCES EMPLOYE (ID),
  CONSTRAINT FK_CTR_POSTE FOREIGN KEY (POSTE_ID)             REFERENCES POSTE (ID),
  CONSTRAINT FK_CTR_PREC  FOREIGN KEY (CONTRAT_PRECEDENT_ID) REFERENCES CONTRAT (ID),
  CONSTRAINT CK_CTR_TYPE   CHECK (TYPE_CONTRAT IN ('CDD','CDI','STAGE','ALTERNANCE')),
  CONSTRAINT CK_CTR_ACTE   CHECK (TYPE_ACTE IN ('INITIAL','AVENANT','RENOUVELLEMENT')),
  CONSTRAINT CK_CTR_PREC   CHECK (TYPE_ACTE = 'INITIAL' OR CONTRAT_PRECEDENT_ID IS NOT NULL),
  CONSTRAINT CK_CTR_FIN    CHECK ((TYPE_CONTRAT = 'CDI' AND DATE_FIN IS NULL)
                               OR (TYPE_CONTRAT <> 'CDI' AND DATE_FIN IS NOT NULL)),
  CONSTRAINT CK_CTR_DATES  CHECK (DATE_FIN IS NULL OR DATE_FIN >= DATE_DEBUT),
  CONSTRAINT CK_CTR_SAL    CHECK (SALAIRE_BRUT >= 0),
  CONSTRAINT CK_CTR_STATUT CHECK (STATUT_CONTRAT IN ('EN_ATTENTE','EN_COURS','RENOUVELE','TERMINE'))
);
-- Un seul contrat EN_COURS par employe
CREATE UNIQUE INDEX UX_CTR_ENCOURS ON CONTRAT
  (CASE WHEN STATUT_CONTRAT = 'EN_COURS' THEN EMPLOYE_ID END);

