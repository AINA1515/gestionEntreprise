/* Acces dossier et pieces pour les managers (lecture de leur equipe). */
INSERT INTO ROLE_PERMISSION (ROLE_ID, PERMISSION_ID)
SELECT r.ID, p.ID FROM ROLE_RH r CROSS JOIN PERMISSION p
WHERE r.CODE = 'MANAGER' AND p.CODE IN ('DOSSIER_CONSULTER_TOUS','DOCUMENT_CONSULTER_TOUS')
  AND NOT EXISTS (SELECT 1 FROM ROLE_PERMISSION rp WHERE rp.ROLE_ID = r.ID AND rp.PERMISSION_ID = p.ID);
COMMIT;
