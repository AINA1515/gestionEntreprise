/* Temps de travail, plannings et historique des affectations. */
CREATE TABLE REGIME_TRAVAIL (
  ID NUMBER(10) PRIMARY KEY,
  CODE VARCHAR2(30) UNIQUE NOT NULL,
  LIBELLE VARCHAR2(120) NOT NULL,
  DESCRIPTION VARCHAR2(500),
  HEURES_HEBDOMADAIRES NUMBER(5,2),
  EST_ACTIF NUMBER(1) DEFAULT 1 NOT NULL
);
CREATE TABLE HORAIRE_TRAVAIL (
  ID NUMBER(10) PRIMARY KEY,
  REGIME_ID NUMBER(10) NOT NULL REFERENCES REGIME_TRAVAIL(ID),
  JOUR_SEMAINE NUMBER(1) NOT NULL,
  HEURE_DEBUT DATE NOT NULL,
  HEURE_FIN DATE NOT NULL,
  PAUSE_MINUTES NUMBER(5) DEFAULT 0 NOT NULL,
  CONSTRAINT CK_HORAIRE_JOUR CHECK (JOUR_SEMAINE BETWEEN 1 AND 7),
  CONSTRAINT CK_HORAIRE_HEURES CHECK (HEURE_FIN > HEURE_DEBUT)
);
CREATE TABLE PLANNING_TRAVAIL (
  ID NUMBER(10) PRIMARY KEY,
  EMPLOYE_ID NUMBER(10) NOT NULL REFERENCES EMPLOYE(ID),
  REGIME_ID NUMBER(10) NOT NULL REFERENCES REGIME_TRAVAIL(ID),
  DATE_DEBUT DATE NOT NULL,
  DATE_FIN DATE,
  ASSIGNE_PAR_ID NUMBER(10) NOT NULL REFERENCES EMPLOYE(ID),
  MOTIF VARCHAR2(500),
  CONSTRAINT CK_PLANNING_DATES CHECK (DATE_FIN IS NULL OR DATE_FIN >= DATE_DEBUT)
);
CREATE TABLE CRENEAU_TRAVAIL (
  ID NUMBER(10) PRIMARY KEY,
  PLANNING_ID NUMBER(10) NOT NULL REFERENCES PLANNING_TRAVAIL(ID),
  DATE_DEBUT TIMESTAMP NOT NULL,
  DATE_FIN TIMESTAMP NOT NULL,
  TYPE_CRENEAU VARCHAR2(20),
  LIBELLE VARCHAR2(200),
  STATUT VARCHAR2(15) DEFAULT 'PLANIFIE' NOT NULL,
  CONSTRAINT CK_CRENEAU_STATUT CHECK (STATUT IN ('PLANIFIE','REALISE','ANNULE'))
);
CREATE TABLE HISTORIQUE_TEMPS_TRAVAIL (
  ID NUMBER(10) PRIMARY KEY,
  EMPLOYE_ID NUMBER(10) NOT NULL REFERENCES EMPLOYE(ID),
  PLANNING_ID NUMBER(10) REFERENCES PLANNING_TRAVAIL(ID),
  ACTION VARCHAR2(20) NOT NULL,
  ANCIENNE_VALEUR VARCHAR2(4000),
  NOUVELLE_VALEUR VARCHAR2(4000),
  MODIFIE_PAR_ID NUMBER(10) NOT NULL REFERENCES EMPLOYE(ID),
  DATE_MODIFICATION TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
