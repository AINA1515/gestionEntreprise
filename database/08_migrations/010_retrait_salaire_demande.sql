/* Le salaire de référence vient du budget estimé de la demande. Supprime la colonne ajoutée par erreur. */
DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM USER_CONSTRAINTS
   WHERE TABLE_NAME = 'DEMANDE_RECRUTEMENT' AND CONSTRAINT_NAME = 'CK_DR_SALAIRE';
  IF v_count > 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE DEMANDE_RECRUTEMENT DROP CONSTRAINT CK_DR_SALAIRE';
  END IF;

  SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS
   WHERE TABLE_NAME = 'DEMANDE_RECRUTEMENT' AND COLUMN_NAME = 'SALAIRE_PROPOSE';
  IF v_count > 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE DEMANDE_RECRUTEMENT DROP COLUMN SALAIRE_PROPOSE';
  END IF;
END;
/
COMMIT;
