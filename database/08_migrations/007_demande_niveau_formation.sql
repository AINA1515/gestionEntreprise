/* Niveau de formation requis pour une demande de recrutement. */
DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS
   WHERE TABLE_NAME = 'DEMANDE_RECRUTEMENT' AND COLUMN_NAME = 'NIVEAU_FORMATION_CODE';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE DEMANDE_RECRUTEMENT ADD (NIVEAU_FORMATION_CODE VARCHAR2(30))';
  END IF;

  SELECT COUNT(*) INTO v_count FROM USER_CONSTRAINTS WHERE CONSTRAINT_NAME = 'FK_DR_NIVEAU_FORMATION';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE DEMANDE_RECRUTEMENT ADD CONSTRAINT FK_DR_NIVEAU_FORMATION FOREIGN KEY (NIVEAU_FORMATION_CODE) REFERENCES NIVEAU_FORMATION (CODE)';
  END IF;
END;
/

COMMIT;
