/* Stockage relationnel des modifications : une ligne par champ modifié. */
CREATE TABLE DEMANDE_MODIFICATION_CHAMP (
  ID NUMBER(10) PRIMARY KEY,
  DEMANDE_ID NUMBER(10) NOT NULL,
  NOM_CHAMP VARCHAR2(60) NOT NULL,
  ANCIENNE_VALEUR VARCHAR2(4000),
  NOUVELLE_VALEUR VARCHAR2(4000),
  CONSTRAINT FK_DMCH_DEMANDE FOREIGN KEY (DEMANDE_ID)
    REFERENCES DEMANDE_MODIFICATION_DOSSIER(ID) ON DELETE CASCADE,
  CONSTRAINT UK_DMCH_CHAMP UNIQUE (DEMANDE_ID, NOM_CHAMP)
);
CREATE SEQUENCE SEQ_DEMANDE_MODIF_CHAMP START WITH 1 INCREMENT BY 1;
CREATE INDEX IX_DMCH_DEMANDE ON DEMANDE_MODIFICATION_CHAMP(DEMANDE_ID);
COMMIT;
