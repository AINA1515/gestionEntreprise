/* Autorise le statut d'annulation volontaire d'une candidature par son candidat. */
DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM USER_CONSTRAINTS
   WHERE TABLE_NAME = 'CANDIDATURE' AND CONSTRAINT_NAME = 'CK_CDT_STATUT';
  IF v_count > 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE CANDIDATURE DROP CONSTRAINT CK_CDT_STATUT';
  END IF;
  EXECUTE IMMEDIATE 'ALTER TABLE CANDIDATURE ADD CONSTRAINT CK_CDT_STATUT CHECK (STATUT_CANDIDATURE IN (''RECUE'',''PRESELECTIONNEE'',''EN_ENTRETIEN'',''RETENUE'',''REJETEE'',''ANNULEE''))';
END;
/
COMMIT;
