/* Référentiel des types d'emploi proposés pour les expériences de CV. */
DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'TYPE_EMPLOI';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE TYPE_EMPLOI (
      CODE VARCHAR2(30) NOT NULL,
      LIBELLE VARCHAR2(100) NOT NULL,
      ORDRE NUMBER(3) NOT NULL,
      EST_ACTIF NUMBER(1) DEFAULT 1 NOT NULL,
      CONSTRAINT PK_TYPE_EMPLOI PRIMARY KEY (CODE),
      CONSTRAINT CK_TYPE_EMPLOI_ACTIF CHECK (EST_ACTIF IN (0,1))
    )';
  END IF;
END;
/

MERGE INTO TYPE_EMPLOI cible
USING (
  SELECT 'CDI' CODE, 'CDI' LIBELLE, 10 ORDRE FROM DUAL UNION ALL
  SELECT 'CDD', 'CDD', 20 FROM DUAL UNION ALL
  SELECT 'INTERIM', 'Intérim', 30 FROM DUAL UNION ALL
  SELECT 'STAGE', 'Stage', 40 FROM DUAL UNION ALL
  SELECT 'ALTERNANCE', 'Alternance', 50 FROM DUAL UNION ALL
  SELECT 'APPRENTISSAGE', 'Apprentissage', 60 FROM DUAL UNION ALL
  SELECT 'FREELANCE', 'Freelance', 70 FROM DUAL UNION ALL
  SELECT 'AUTRE', 'Autre', 80 FROM DUAL
) source
ON (cible.CODE = source.CODE)
WHEN MATCHED THEN UPDATE SET cible.LIBELLE = source.LIBELLE, cible.ORDRE = source.ORDRE
WHEN NOT MATCHED THEN INSERT (CODE, LIBELLE, ORDRE, EST_ACTIF)
  VALUES (source.CODE, source.LIBELLE, source.ORDRE, 1);

COMMIT;
