/* Enregistre le salaire éventuellement proposé par le candidat. NULL signifie qu'il accepte le budget de référence. */
DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS
   WHERE TABLE_NAME = 'CANDIDATURE' AND COLUMN_NAME = 'SALAIRE_PROPOSE';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE CANDIDATURE ADD (SALAIRE_PROPOSE NUMBER(15,2))';
  END IF;

  SELECT COUNT(*) INTO v_count FROM USER_CONSTRAINTS WHERE CONSTRAINT_NAME = 'CK_CDT_SALAIRE';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE CANDIDATURE ADD CONSTRAINT CK_CDT_SALAIRE CHECK (SALAIRE_PROPOSE IS NULL OR SALAIRE_PROPOSE >= 0)';
  END IF;
END;
/
COMMIT;
