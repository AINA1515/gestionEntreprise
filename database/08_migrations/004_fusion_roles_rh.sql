/* Fusion des roles CHARGE_RECRUTEMENT et GESTIONNAIRE_RH.
   Les utilisateurs rattaches a l'ancien role obtiennent les permissions RH
   unifiees avant la desactivation de CHARGE_RECRUTEMENT. */

INSERT INTO ROLE_PERMISSION (ROLE_ID, PERMISSION_ID)
SELECT rh.ID, p.ID
  FROM ROLE_RH rh
  JOIN PERMISSION p ON p.CODE IN (
    'DEMANDE_CONSULTER', 'DEMANDE_VERIFIER_RH', 'OFFRE_PUBLIER',
    'CANDIDATURE_CONSULTER', 'CANDIDATURE_PRESELECTIONNER', 'ENTRETIEN_PLANIFIER',
    'PROPOSITION_EMETTRE', 'EMPLOYE_CONVERTIR', 'CONTRAT_GERER', 'ONBOARDING_ADMIN',
    'TACHE_TRAITER', 'DOCUMENT_CONSULTER_TOUS', 'DOCUMENT_CONSULTER_PERSO')
 WHERE rh.CODE = 'GESTIONNAIRE_RH'
   AND NOT EXISTS (SELECT 1 FROM ROLE_PERMISSION rp WHERE rp.ROLE_ID = rh.ID AND rp.PERMISSION_ID = p.ID);

INSERT INTO UTILISATEUR_ROLE (UTILISATEUR_ID, ROLE_ID, DATE_DEBUT, MOTIF)
SELECT ur.UTILISATEUR_ID, rh.ID, TRUNC(SYSDATE), 'Fusion des roles RH'
  FROM UTILISATEUR_ROLE ur
  JOIN ROLE_RH ancien ON ancien.ID = ur.ROLE_ID AND ancien.CODE = 'CHARGE_RECRUTEMENT'
  JOIN ROLE_RH rh ON rh.CODE = 'GESTIONNAIRE_RH'
 WHERE ur.DATE_FIN IS NULL
   AND NOT EXISTS (
       SELECT 1 FROM UTILISATEUR_ROLE existant
        WHERE existant.UTILISATEUR_ID = ur.UTILISATEUR_ID
          AND existant.ROLE_ID = rh.ID
          AND existant.DATE_FIN IS NULL);

-- Préserve l'historique tout en évitant deux rôles RH actifs à la même date.
UPDATE UTILISATEUR_ROLE ancien
   SET DATE_FIN = TRUNC(SYSDATE), MOTIF = 'Fusion des roles RH'
 WHERE ancien.DATE_FIN IS NULL
   AND ancien.ROLE_ID IN (SELECT ID FROM ROLE_RH WHERE CODE = 'CHARGE_RECRUTEMENT')
   AND EXISTS (
       SELECT 1 FROM UTILISATEUR_ROLE rh
        WHERE rh.UTILISATEUR_ID = ancien.UTILISATEUR_ID
          AND rh.ROLE_ID IN (SELECT ID FROM ROLE_RH WHERE CODE = 'GESTIONNAIRE_RH')
          AND rh.DATE_FIN IS NULL);

UPDATE UTILISATEUR_ROLE ur
   SET DATE_FIN = TRUNC(SYSDATE), MOTIF = 'Fusion des roles RH'
 WHERE ur.DATE_FIN IS NULL
   AND ur.ROLE_ID IN (SELECT ID FROM ROLE_RH WHERE CODE = 'CHARGE_RECRUTEMENT');

-- Désactivation appliquée après le transfert dans database/gestion_rh.sql.

DELETE FROM ROLE_RH WHERE CODE = 'CHARGE_RECRUTEMENT';

COMMIT;
