/* Workflow de validation hiérarchique des modifications du dossier salarié. */
CREATE TABLE DEMANDE_MODIFICATION_DOSSIER (
  ID NUMBER(10) PRIMARY KEY,
  EMPLOYE_ID NUMBER(10) NOT NULL,
  SUPERIEUR_ID NUMBER(10) NOT NULL,
  ANCIENNES_VALEURS CLOB,
  NOUVELLES_VALEURS CLOB,
  STATUT VARCHAR2(15) DEFAULT 'EN_ATTENTE' NOT NULL,
  MOTIF VARCHAR2(500),
  DATE_DEMANDE DATE DEFAULT SYSDATE NOT NULL,
  DATE_DECISION DATE,
  DECIDE_PAR_ID NUMBER(10),
  CONSTRAINT CK_DMD_STATUT CHECK (STATUT IN ('EN_ATTENTE','ACCEPTEE','REFUSEE')),
  CONSTRAINT FK_DMD_EMP FOREIGN KEY (EMPLOYE_ID) REFERENCES EMPLOYE(ID),
  CONSTRAINT FK_DMD_SUP FOREIGN KEY (SUPERIEUR_ID) REFERENCES EMPLOYE(ID),
  CONSTRAINT FK_DMD_DEC FOREIGN KEY (DECIDE_PAR_ID) REFERENCES EMPLOYE(ID)
);
CREATE SEQUENCE SEQ_DEMANDE_MODIF_DOSSIER START WITH 1 INCREMENT BY 1;
CREATE INDEX IX_DMD_SUP_STATUT ON DEMANDE_MODIFICATION_DOSSIER(SUPERIEUR_ID, STATUT);
CREATE INDEX IX_DMD_EMP_DATE ON DEMANDE_MODIFICATION_DOSSIER(EMPLOYE_ID, DATE_DEMANDE);
COMMIT;
