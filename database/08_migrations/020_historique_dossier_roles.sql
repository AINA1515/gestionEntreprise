/* Historique des changements consultable par RH, managers et salarié concerné. */
INSERT INTO ROLE_PERMISSION (ROLE_ID, PERMISSION_ID)
SELECT r.ID,p.ID FROM ROLE_RH r CROSS JOIN PERMISSION p
WHERE r.CODE IN ('GESTIONNAIRE_RH','MANAGER','SALARIE') AND p.CODE='AUDIT_CONSULTER'
AND NOT EXISTS (SELECT 1 FROM ROLE_PERMISSION x WHERE x.ROLE_ID=r.ID AND x.PERMISSION_ID=p.ID);
COMMIT;
