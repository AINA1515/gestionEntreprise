/* Référentiel des niveaux sélectionnables pour chaque formation de CV. */
DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'NIVEAU_FORMATION';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE NIVEAU_FORMATION (
      CODE VARCHAR2(30) NOT NULL,
      LIBELLE VARCHAR2(100) NOT NULL,
      ORDRE NUMBER(3) NOT NULL,
      EST_ACTIF NUMBER(1) DEFAULT 1 NOT NULL,
      CONSTRAINT PK_NIVEAU_FORMATION PRIMARY KEY (CODE),
      CONSTRAINT CK_NIV_FORM_ACTIF CHECK (EST_ACTIF IN (0,1))
    )';
  END IF;
END;
/

MERGE INTO NIVEAU_FORMATION cible
USING (
  SELECT 'DEBUTANT' CODE, 'Débutant' LIBELLE, 10 ORDRE FROM DUAL UNION ALL
  SELECT 'INTERMEDIAIRE', 'Intermédiaire', 20 FROM DUAL UNION ALL
  SELECT 'AVANCE', 'Avancé', 30 FROM DUAL UNION ALL
  SELECT 'EXPERT', 'Expert', 40 FROM DUAL UNION ALL
  SELECT 'MAITRISE', 'Maîtrise', 50 FROM DUAL
) source
ON (cible.CODE = source.CODE)
WHEN MATCHED THEN UPDATE SET cible.LIBELLE = source.LIBELLE, cible.ORDRE = source.ORDRE
WHEN NOT MATCHED THEN INSERT (CODE, LIBELLE, ORDRE, EST_ACTIF)
  VALUES (source.CODE, source.LIBELLE, source.ORDRE, 1);

COMMIT;
