/* Pointage quotidien, retards et heures supplémentaires. */
CREATE TABLE POINTAGE_JOURNALIER (
  ID NUMBER(10) PRIMARY KEY,
  EMPLOYE_ID NUMBER(10) NOT NULL REFERENCES EMPLOYE(ID),
  DATE_POINTAGE DATE NOT NULL,
  ENTREE_PREVUE TIMESTAMP,
  SORTIE_PREVUE TIMESTAMP,
  ENTREE_REELLE TIMESTAMP,
  SORTIE_REELLE TIMESTAMP,
  MINUTES_RETARD NUMBER(6) DEFAULT 0 NOT NULL,
  MINUTES_HEURES_SUP NUMBER(6) DEFAULT 0 NOT NULL,
  STATUT VARCHAR2(15) DEFAULT 'ABSENT' NOT NULL,
  SAISI_PAR_ID NUMBER(10) REFERENCES EMPLOYE(ID),
  DATE_SAISIE TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT UK_POINTAGE_EMP_DATE UNIQUE (EMPLOYE_ID, DATE_POINTAGE),
  CONSTRAINT CK_POINTAGE_STATUT CHECK (STATUT IN ('ABSENT','PRESENT','RETARD','CONGE','JUSTIFIE'))
);
CREATE TABLE HISTORIQUE_POINTAGE (
  ID NUMBER(10) PRIMARY KEY,
  POINTAGE_ID NUMBER(10) NOT NULL REFERENCES POINTAGE_JOURNALIER(ID),
  EMPLOYE_ID NUMBER(10) NOT NULL REFERENCES EMPLOYE(ID),
  ACTION VARCHAR2(20) NOT NULL,
  ANCIENNE_VALEUR VARCHAR2(4000),
  NOUVELLE_VALEUR VARCHAR2(4000),
  MODIFIE_PAR_ID NUMBER(10) NOT NULL REFERENCES EMPLOYE(ID),
  DATE_MODIFICATION TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE SEQUENCE SEQ_POINTAGE_JOURNALIER START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SEQ_HISTORIQUE_POINTAGE START WITH 1 INCREMENT BY 1;
CREATE INDEX IX_POINTAGE_DATE ON POINTAGE_JOURNALIER(DATE_POINTAGE);
CREATE INDEX IX_POINTAGE_EMP ON POINTAGE_JOURNALIER(EMPLOYE_ID, DATE_POINTAGE);
COMMIT;
