/* Types d'emploi = domaines d'activité (informatique, finance...), utilisés dans les expériences du CV
   et sur les demandes de recrutement pour la présélection automatique.
   Les anciennes valeurs de type de contrat (CDI, CDD...) sont désactivées, pas supprimées :
   les CV déjà enregistrés restent lisibles. */
UPDATE TYPE_EMPLOI SET EST_ACTIF = 0
 WHERE CODE IN ('CDI','CDD','INTERIM','STAGE','ALTERNANCE','APPRENTISSAGE','FREELANCE');

MERGE INTO TYPE_EMPLOI cible
USING (
  SELECT 'INFORMATIQUE' CODE, 'Informatique' LIBELLE, 10 ORDRE FROM DUAL UNION ALL
  SELECT 'FINANCE_COMPTABILITE', 'Finance et comptabilité', 20 FROM DUAL UNION ALL
  SELECT 'RESSOURCES_HUMAINES', 'Ressources humaines', 30 FROM DUAL UNION ALL
  SELECT 'COMMERCIAL_MARKETING', 'Commercial et marketing', 40 FROM DUAL UNION ALL
  SELECT 'JURIDIQUE', 'Juridique', 50 FROM DUAL UNION ALL
  SELECT 'LOGISTIQUE_TRANSPORT', 'Logistique et transport', 60 FROM DUAL UNION ALL
  SELECT 'BTP_INDUSTRIE', 'BTP et industrie', 70 FROM DUAL UNION ALL
  SELECT 'SANTE', 'Santé', 80 FROM DUAL UNION ALL
  SELECT 'EDUCATION_FORMATION', 'Éducation et formation', 90 FROM DUAL UNION ALL
  SELECT 'HOTELLERIE_RESTAURATION', 'Hôtellerie et restauration', 100 FROM DUAL UNION ALL
  SELECT 'AUTRE', 'Autre', 110 FROM DUAL
) source
ON (cible.CODE = source.CODE)
WHEN MATCHED THEN UPDATE SET cible.LIBELLE = source.LIBELLE, cible.ORDRE = source.ORDRE, cible.EST_ACTIF = 1
WHEN NOT MATCHED THEN INSERT (CODE, LIBELLE, ORDRE, EST_ACTIF)
  VALUES (source.CODE, source.LIBELLE, source.ORDRE, 1);

DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS
   WHERE TABLE_NAME = 'DEMANDE_RECRUTEMENT' AND COLUMN_NAME = 'TYPE_EMPLOI_CODE';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE DEMANDE_RECRUTEMENT ADD (TYPE_EMPLOI_CODE VARCHAR2(30))';
  END IF;

  SELECT COUNT(*) INTO v_count FROM USER_CONSTRAINTS WHERE CONSTRAINT_NAME = 'FK_DR_TYPE_EMPLOI';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE DEMANDE_RECRUTEMENT ADD CONSTRAINT FK_DR_TYPE_EMPLOI FOREIGN KEY (TYPE_EMPLOI_CODE) REFERENCES TYPE_EMPLOI (CODE)';
  END IF;
END;
/

COMMIT;
