-- Les comptes convertis apres embauche sont des comptes SALARIE.
ALTER TABLE UTILISATEUR DROP CONSTRAINT CK_UTIL_TYPE;
ALTER TABLE UTILISATEUR ADD CONSTRAINT CK_UTIL_TYPE
  CHECK (TYPE_COMPTE IN ('INTERNE','CANDIDAT','SALARIE'));
UPDATE UTILISATEUR
   SET TYPE_COMPTE = 'SALARIE'
 WHERE EMPLOYE_ID IS NOT NULL
   AND TYPE_COMPTE = 'CANDIDAT';

UPDATE UTILISATEUR_ROLE ur
   SET DATE_FIN = GREATEST(ur.DATE_DEBUT, TRUNC(SYSDATE) - 1)
 WHERE ur.DATE_FIN IS NULL
   AND EXISTS (SELECT 1 FROM ROLE_RH r WHERE r.ID = ur.ROLE_ID AND r.CODE = 'CANDIDAT')
   AND EXISTS (SELECT 1 FROM UTILISATEUR u WHERE u.ID = ur.UTILISATEUR_ID AND u.EMPLOYE_ID IS NOT NULL);

UPDATE UTILISATEUR_ROLE ur
   SET DATE_DEBUT = TRUNC(SYSDATE)
 WHERE ur.DATE_FIN IS NULL
   AND ur.DATE_DEBUT > TRUNC(SYSDATE)
   AND EXISTS (SELECT 1 FROM ROLE_RH r WHERE r.ID = ur.ROLE_ID AND r.CODE = 'SALARIE')
   AND EXISTS (SELECT 1 FROM UTILISATEUR u WHERE u.ID = ur.UTILISATEUR_ID AND u.EMPLOYE_ID IS NOT NULL);

MERGE INTO UTILISATEUR_ROLE ur
USING (
  SELECT u.ID UTILISATEUR_ID, r.ID ROLE_ID
    FROM UTILISATEUR u CROSS JOIN ROLE_RH r
   WHERE u.EMPLOYE_ID IS NOT NULL AND r.CODE = 'SALARIE'
     AND NOT EXISTS (SELECT 1 FROM UTILISATEUR_ROLE existant
                      WHERE existant.UTILISATEUR_ID = u.ID
                        AND existant.ROLE_ID = r.ID AND existant.DATE_FIN IS NULL)
) source
ON (ur.UTILISATEUR_ID = source.UTILISATEUR_ID AND ur.ROLE_ID = source.ROLE_ID
    AND ur.DATE_DEBUT = TRUNC(SYSDATE))
WHEN NOT MATCHED THEN INSERT (ID, UTILISATEUR_ID, ROLE_ID, DATE_DEBUT, MOTIF)
VALUES (SEQ_UTILISATEUR_ROLE.NEXTVAL, source.UTILISATEUR_ID, source.ROLE_ID,
        TRUNC(SYSDATE), 'Activation espace salarié pour les comptes déjà embauchés');

-- Etapes explicites attendues dans le parcours d'integration.
MERGE INTO MODELE_ONB_TACHE cible
USING (
  SELECT 'RH_CONTRAT_SIGNE' CODE, 'Contrat de travail signe' INTITULE,
         'RH' SERVICE_RESPONSABLE, 0 DELAI_JOURS, 1 EST_OBLIGATOIRE, 5 ORDRE FROM DUAL
  UNION ALL
  SELECT 'IT_COMPTE', 'Creation et activation du compte employe', 'IT', 0, 1, 35 FROM DUAL
  UNION ALL
  SELECT 'RH_FORMATION', 'Inscription aux formations d''integration', 'RH', 10, 1, 65 FROM DUAL
) source
ON (cible.CODE = source.CODE)
WHEN MATCHED THEN UPDATE SET
  cible.INTITULE = source.INTITULE,
  cible.SERVICE_RESPONSABLE = source.SERVICE_RESPONSABLE,
  cible.DELAI_JOURS = source.DELAI_JOURS,
  cible.EST_OBLIGATOIRE = source.EST_OBLIGATOIRE,
  cible.ORDRE = source.ORDRE,
  cible.EST_ACTIF = 1
WHEN NOT MATCHED THEN INSERT
  (ID, CODE, INTITULE, SERVICE_RESPONSABLE, DELAI_JOURS, EST_OBLIGATOIRE, ORDRE, EST_ACTIF)
VALUES
  (SEQ_MODELE_ONB_TACHE.NEXTVAL, source.CODE, source.INTITULE,
   source.SERVICE_RESPONSABLE, source.DELAI_JOURS, source.EST_OBLIGATOIRE, source.ORDRE, 1);

COMMIT;
