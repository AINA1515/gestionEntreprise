PROMPT === 5. GED / Notifications ===

-- Metadonnees des fichiers (le binaire reste dans la GED, on garde URL + empreinte).
-- Rattachement polymorphe (ENTITE_RATTACHEMENT + ENTITE_ID) : pas de FK, controle applicatif.
CREATE TABLE DOCUMENT (
  ID                     NUMBER(10)     NOT NULL,
  NOM_FICHIER            VARCHAR2(255)  NOT NULL,
  TYPE_DOCUMENT          VARCHAR2(25)   NOT NULL,
  ENTITE_RATTACHEMENT    VARCHAR2(30)   NOT NULL,
  ENTITE_ID              NUMBER(10)     NOT NULL,
  URL_STOCKAGE_GED       VARCHAR2(1000) NOT NULL,
  TYPE_MIME              VARCHAR2(100),
  TAILLE_OCTETS          NUMBER(12),
  EMPREINTE_SHA256       VARCHAR2(64),
  NUMERO_VERSION         NUMBER(5)      DEFAULT 1 NOT NULL,
  DOCUMENT_PRECEDENT_ID  NUMBER(10),
  CONFIDENTIALITE        VARCHAR2(12)   DEFAULT 'INTERNE' NOT NULL,
  STATUT_DOCUMENT        VARCHAR2(10)   DEFAULT 'ACTIF' NOT NULL,
  CONSTRAINT PK_DOCUMENT PRIMARY KEY (ID),
  CONSTRAINT FK_DOC_PREC FOREIGN KEY (DOCUMENT_PRECEDENT_ID) REFERENCES DOCUMENT (ID),
  CONSTRAINT CK_DOC_TYPE CHECK (TYPE_DOCUMENT IN ('CV','LETTRE_MOTIVATION','CONTRAT_SIGNE','RIB',
      'PIECE_IDENTITE','CARTE_VITALE','REGLEMENT_SIGNE','FICHE_POSTE','PROPOSITION','AUTRE')),
  CONSTRAINT CK_DOC_ENTITE CHECK (ENTITE_RATTACHEMENT IN ('CANDIDAT','CANDIDATURE','EMPLOYE','CONTRAT',
      'ONBOARDING_TACHE','POSTE','PROPOSITION_EMBAUCHE')),
  CONSTRAINT CK_DOC_CONF   CHECK (CONFIDENTIALITE IN ('INTERNE','CONFIDENTIEL','STRICT')),
  CONSTRAINT CK_DOC_STATUT CHECK (STATUT_DOCUMENT IN ('ACTIF','ARCHIVE','SUPPRIME'))
);

-- File d'attente d'e-mails / notifications envoyes par le service dedie.
CREATE TABLE NOTIFICATION (
  ID                   NUMBER(10)     NOT NULL,
  DESTINATAIRE_ID      NUMBER(10),
  DESTINATAIRE_EMAIL   VARCHAR2(150)  NOT NULL,
  SUJET                VARCHAR2(250)  NOT NULL,
  CORPS                CLOB,
  CODE_MODELE          VARCHAR2(50),
  ENTITE_RATTACHEMENT  VARCHAR2(30),
  ENTITE_ID            NUMBER(10),
  STATUT_ENVOI         VARCHAR2(10)   DEFAULT 'EN_ATTENTE' NOT NULL,
  NB_TENTATIVES        NUMBER(3)      DEFAULT 0 NOT NULL,
  DATE_ENVOI_PREVUE    TIMESTAMP(6)   DEFAULT SYSTIMESTAMP NOT NULL,
  DATE_ENVOI_REEL      TIMESTAMP(6),
  MESSAGE_ERREUR       VARCHAR2(1000),
  CONSTRAINT PK_NOTIFICATION PRIMARY KEY (ID),
  CONSTRAINT FK_NOTIF_DEST FOREIGN KEY (DESTINATAIRE_ID) REFERENCES UTILISATEUR (ID),
  CONSTRAINT CK_NOTIF_STATUT CHECK (STATUT_ENVOI IN ('EN_ATTENTE','ENVOYEE','ECHEC'))
);

-- Compteur annuel pour le matricule EMP-AAAA-NNNN (sans trou, sans doublon).
CREATE TABLE COMPTEUR_MATRICULE (
  ANNEE           NUMBER(4)  NOT NULL,
  DERNIER_NUMERO  NUMBER(6)  DEFAULT 0 NOT NULL,
  CONSTRAINT PK_COMPTEUR_MATRICULE PRIMARY KEY (ANNEE)
);
