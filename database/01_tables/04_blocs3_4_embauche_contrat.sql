CREATE TABLE PROPOSITION_EMBAUCHE (
  ID                      NUMBER(10)     NOT NULL,
  CANDIDATURE_ID          NUMBER(10)     NOT NULL,
  REDACTEUR_ID            NUMBER(10),
  TYPE_CONTRAT_PROPOSE    VARCHAR2(12)   NOT NULL,
  SALAIRE_BRUT_PROPOSE    NUMBER(15,2),
  DATE_DEBUT_SOUHAITEE    DATE,
  DATE_FIN_SOUHAITEE      DATE,
  DATE_ENVOI              DATE,
  DATE_LIMITE_REPONSE     DATE,
  DATE_REPONSE            DATE,
  MOTIF_REFUS             VARCHAR2(500),
  EMPLOYE_ID              NUMBER(10),
  STATUT_PROPOSITION      VARCHAR2(10)   DEFAULT 'BROUILLON' NOT NULL,
  CONSTRAINT PK_PROPOSITION_EMBAUCHE PRIMARY KEY (ID),
  CONSTRAINT FK_PROP_CDT   FOREIGN KEY (CANDIDATURE_ID) REFERENCES CANDIDATURE (ID),
  CONSTRAINT FK_PROP_REDAC FOREIGN KEY (REDACTEUR_ID)   REFERENCES UTILISATEUR (ID),
  CONSTRAINT FK_PROP_EMP   FOREIGN KEY (EMPLOYE_ID)     REFERENCES EMPLOYE (ID),
  CONSTRAINT CK_PROP_TYPE   CHECK (TYPE_CONTRAT_PROPOSE IN ('CDD','CDI','STAGE','ALTERNANCE')),
  CONSTRAINT CK_PROP_SAL    CHECK (SALAIRE_BRUT_PROPOSE IS NULL OR SALAIRE_BRUT_PROPOSE >= 0),
  CONSTRAINT CK_PROP_STATUT CHECK (STATUT_PROPOSITION IN
      ('BROUILLON','ENVOYEE','ACCEPTEE','REFUSEE','EXPIREE','ANNULEE'))
);

-- 1 ligne = 1 acte contractuel (initial, avenant, renouvellement). Jamais d'ecrasement.
CREATE TABLE CONTRAT (
  ID                     NUMBER(10)     NOT NULL,
  EMPLOYE_ID             NUMBER(10)     NOT NULL,
  POSTE_ID               NUMBER(10)     NOT NULL,
  TYPE_CONTRAT           VARCHAR2(12)   NOT NULL,
  TYPE_ACTE              VARCHAR2(15)   DEFAULT 'INITIAL' NOT NULL,
  CONTRAT_PRECEDENT_ID   NUMBER(10),
  DATE_DEBUT             DATE           NOT NULL,
  DATE_FIN               DATE,
  DATE_FIN_EFFECTIVE     DATE,
  SALAIRE_BRUT           NUMBER(15,2)   NOT NULL,
  DEVISE                 VARCHAR2(3)    DEFAULT 'EUR' NOT NULL,   -- adapter a la devise locale
  STATUT_CONTRAT         VARCHAR2(12)   DEFAULT 'EN_ATTENTE' NOT NULL,
  CONSTRAINT PK_CONTRAT PRIMARY KEY (ID),
  CONSTRAINT FK_CTR_EMP   FOREIGN KEY (EMPLOYE_ID)           REFERENCES EMPLOYE (ID),
  CONSTRAINT FK_CTR_POSTE FOREIGN KEY (POSTE_ID)             REFERENCES POSTE (ID),
  CONSTRAINT FK_CTR_PREC  FOREIGN KEY (CONTRAT_PRECEDENT_ID) REFERENCES CONTRAT (ID),
  CONSTRAINT CK_CTR_TYPE   CHECK (TYPE_CONTRAT IN ('CDD','CDI','STAGE','ALTERNANCE')),
  CONSTRAINT CK_CTR_ACTE   CHECK (TYPE_ACTE IN ('INITIAL','AVENANT','RENOUVELLEMENT')),
  CONSTRAINT CK_CTR_PREC   CHECK (TYPE_ACTE = 'INITIAL' OR CONTRAT_PRECEDENT_ID IS NOT NULL),
  CONSTRAINT CK_CTR_FIN    CHECK ((TYPE_CONTRAT = 'CDI' AND DATE_FIN IS NULL)
                               OR (TYPE_CONTRAT <> 'CDI' AND DATE_FIN IS NOT NULL)),
  CONSTRAINT CK_CTR_DATES  CHECK (DATE_FIN IS NULL OR DATE_FIN >= DATE_DEBUT),
  CONSTRAINT CK_CTR_SAL    CHECK (SALAIRE_BRUT >= 0),
  CONSTRAINT CK_CTR_STATUT CHECK (STATUT_CONTRAT IN ('EN_ATTENTE','EN_COURS','RENOUVELE','TERMINE'))
);
-- Un seul contrat EN_COURS par employe
CREATE UNIQUE INDEX UX_CTR_ENCOURS ON CONTRAT
  (CASE WHEN STATUT_CONTRAT = 'EN_COURS' THEN EMPLOYE_ID END);

-- Historique des affectations employe <-> poste (et hierarchie manager).
CREATE TABLE AFFECTATION (
  ID           NUMBER(10)    NOT NULL,
  EMPLOYE_ID   NUMBER(10)    NOT NULL,
  POSTE_ID     NUMBER(10)    NOT NULL,
  CONTRAT_ID   NUMBER(10),
  SUPERIEUR_ID NUMBER(10),
  DATE_DEBUT   DATE          NOT NULL,
  DATE_FIN     DATE,
  MOTIF        VARCHAR2(300),
  CONSTRAINT PK_AFFECTATION PRIMARY KEY (ID),
  CONSTRAINT FK_AFF_EMP   FOREIGN KEY (EMPLOYE_ID)   REFERENCES EMPLOYE (ID),
  CONSTRAINT FK_AFF_POSTE FOREIGN KEY (POSTE_ID)     REFERENCES POSTE (ID),
  CONSTRAINT FK_AFF_CTR   FOREIGN KEY (CONTRAT_ID)   REFERENCES CONTRAT (ID),
  CONSTRAINT FK_AFF_SUP   FOREIGN KEY (SUPERIEUR_ID) REFERENCES EMPLOYE (ID),
  CONSTRAINT CK_AFF_DATES CHECK (DATE_FIN IS NULL OR DATE_FIN >= DATE_DEBUT)
);
-- Une seule affectation courante (DATE_FIN nulle) par employe
CREATE UNIQUE INDEX UX_AFF_COURANTE ON AFFECTATION
  (CASE WHEN DATE_FIN IS NULL THEN EMPLOYE_ID END);

-- Catalogue de taches type, utilise pour generer automatiquement une checklist.
CREATE TABLE MODELE_ONB_TACHE (
  ID                   NUMBER(10)      NOT NULL,
  CODE                 VARCHAR2(40)    NOT NULL,
  INTITULE             VARCHAR2(250)   NOT NULL,
  DESCRIPTION          VARCHAR2(1000),
  SERVICE_RESPONSABLE  VARCHAR2(20)    NOT NULL,
  DELAI_JOURS          NUMBER(3)       DEFAULT 0 NOT NULL,    -- echeance = date debut + delai
  EST_OBLIGATOIRE      NUMBER(1)       DEFAULT 1 NOT NULL,
  ORDRE                NUMBER(3)       DEFAULT 0 NOT NULL,
  EST_ACTIF            NUMBER(1)       DEFAULT 1 NOT NULL,
  CONSTRAINT PK_MODELE_ONB_TACHE PRIMARY KEY (ID),
  CONSTRAINT UK_MOT_CODE UNIQUE (CODE),
  CONSTRAINT CK_MOT_SERV CHECK (SERVICE_RESPONSABLE IN ('RH','IT','MANAGER','MOYENS_GENERAUX','SALARIE')),
  CONSTRAINT CK_MOT_OBLIG CHECK (EST_OBLIGATOIRE IN (0,1)),
  CONSTRAINT CK_MOT_ACTIF CHECK (EST_ACTIF IN (0,1))
);

CREATE TABLE ONBOARDING (
  ID                NUMBER(10)   NOT NULL,
  EMPLOYE_ID        NUMBER(10)   NOT NULL,
  DATE_DEBUT        DATE         NOT NULL,
  DATE_FIN_PREVUE   DATE         NOT NULL,
  DATE_FIN_REELLE   DATE,
  STATUT_GLOBAL     VARCHAR2(12) DEFAULT 'NON_DEBUTE' NOT NULL,
  CONSTRAINT PK_ONBOARDING PRIMARY KEY (ID),
  CONSTRAINT UK_ONB_EMP UNIQUE (EMPLOYE_ID),               -- Employe 1 --- 1 Onboarding
  CONSTRAINT FK_ONB_EMP FOREIGN KEY (EMPLOYE_ID) REFERENCES EMPLOYE (ID),
  CONSTRAINT CK_ONB_DATES  CHECK (DATE_FIN_PREVUE >= DATE_DEBUT),
  CONSTRAINT CK_ONB_STATUT CHECK (STATUT_GLOBAL IN ('NON_DEBUTE','EN_COURS','COMPLETE'))
);

CREATE TABLE ONBOARDING_TACHE (
  ID                   NUMBER(10)      NOT NULL,
  ONBOARDING_ID        NUMBER(10)      NOT NULL,
  MODELE_ID            NUMBER(10),
  INTITULE_TACHE       VARCHAR2(250)   NOT NULL,
  DESCRIPTION          VARCHAR2(1000),
  SERVICE_RESPONSABLE  VARCHAR2(20)    NOT NULL,
  ASSIGNEE_A_ID        NUMBER(10),
  EST_OBLIGATOIRE      NUMBER(1)       DEFAULT 1 NOT NULL,
  STATUT_TACHE         VARCHAR2(10)    DEFAULT 'A_FAIRE' NOT NULL,
  DATE_LIMITE          DATE,
  DATE_REALISATION     DATE,
  COMMENTAIRE          VARCHAR2(1000),
  CONSTRAINT PK_ONBOARDING_TACHE PRIMARY KEY (ID),
  CONSTRAINT FK_TACHE_ONB   FOREIGN KEY (ONBOARDING_ID) REFERENCES ONBOARDING (ID),
  CONSTRAINT FK_TACHE_MOD   FOREIGN KEY (MODELE_ID)     REFERENCES MODELE_ONB_TACHE (ID),
  CONSTRAINT FK_TACHE_ASSIG FOREIGN KEY (ASSIGNEE_A_ID) REFERENCES UTILISATEUR (ID),
  CONSTRAINT CK_TACHE_SERV   CHECK (SERVICE_RESPONSABLE IN ('RH','IT','MANAGER','MOYENS_GENERAUX','SALARIE')),
  CONSTRAINT CK_TACHE_OBLIG  CHECK (EST_OBLIGATOIRE IN (0,1)),
  CONSTRAINT CK_TACHE_STATUT CHECK (STATUT_TACHE IN ('A_FAIRE','EN_COURS','VALIDEE'))
);
