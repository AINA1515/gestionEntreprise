CREATE TABLE OFFRE_EMPLOI (
  ID                       NUMBER(10)      NOT NULL,
  DEMANDE_RECRUTEMENT_ID   NUMBER(10)      NOT NULL,
  TITRE                    VARCHAR2(250)   NOT NULL,
  DESCRIPTION_POSTE        VARCHAR2(4000),
  PROFIL_RECHERCHE         VARCHAR2(4000),
  DIFFUSION                VARCHAR2(10)    DEFAULT 'EXTERNE' NOT NULL,
  DATE_PUBLICATION         DATE,
  DATE_LIMITE_CANDIDATURE  DATE,
  DATE_CLOTURE             DATE,
  STATUT_OFFRE             VARCHAR2(10)    DEFAULT 'BROUILLON' NOT NULL,
  CONSTRAINT PK_OFFRE_EMPLOI PRIMARY KEY (ID),
  CONSTRAINT FK_OFFRE_DR FOREIGN KEY (DEMANDE_RECRUTEMENT_ID) REFERENCES DEMANDE_RECRUTEMENT (ID),
  CONSTRAINT CK_OFFRE_DIFF   CHECK (DIFFUSION IN ('INTERNE','EXTERNE','MIXTE')),
  CONSTRAINT CK_OFFRE_STATUT CHECK (STATUT_OFFRE IN ('BROUILLON','PUBLIEE','CLOTUREE'))
);

CREATE TABLE CANDIDATURE (
  ID                  NUMBER(10)      NOT NULL,
  OFFRE_ID            NUMBER(10)      NOT NULL,
  CANDIDAT_ID         NUMBER(10)      NOT NULL,
  DATE_POSTULATION    DATE            DEFAULT SYSDATE NOT NULL,
  LETTRE_MOTIVATION   VARCHAR2(4000),
  RECRUTEUR_ID        NUMBER(10),
  STATUT_CANDIDATURE  VARCHAR2(20)    DEFAULT 'RECUE' NOT NULL,
  MOTIF_REJET         VARCHAR2(500),
  CONSTRAINT PK_CANDIDATURE PRIMARY KEY (ID),
  CONSTRAINT UK_CDT_OFFRE_CAND UNIQUE (OFFRE_ID, CANDIDAT_ID),
  CONSTRAINT FK_CDT_OFFRE FOREIGN KEY (OFFRE_ID)    REFERENCES OFFRE_EMPLOI (ID),
  CONSTRAINT FK_CDT_CAND  FOREIGN KEY (CANDIDAT_ID) REFERENCES CANDIDAT (ID),
  CONSTRAINT FK_CDT_RECR  FOREIGN KEY (RECRUTEUR_ID) REFERENCES UTILISATEUR (ID),
  CONSTRAINT CK_CDT_STATUT CHECK (STATUT_CANDIDATURE IN
      ('RECUE','PRESELECTIONNEE','EN_ENTRETIEN','RETENUE','REJETEE'))
);

CREATE TABLE ENTRETIEN (
  ID               NUMBER(10)     NOT NULL,
  CANDIDATURE_ID   NUMBER(10)     NOT NULL,
  INTERVENANT_ID   NUMBER(10)     NOT NULL,
  TYPE_ENTRETIEN   VARCHAR2(10)   DEFAULT 'TECHNIQUE' NOT NULL,
  DATE_ENTRETIEN   DATE           NOT NULL,
  LIEU             VARCHAR2(200),
  STATUT_ENTRETIEN VARCHAR2(10)   DEFAULT 'PLANIFIE' NOT NULL,
  CONSTRAINT PK_ENTRETIEN PRIMARY KEY (ID),
  CONSTRAINT FK_ENT_CDT  FOREIGN KEY (CANDIDATURE_ID) REFERENCES CANDIDATURE (ID),
  CONSTRAINT FK_ENT_INTV FOREIGN KEY (INTERVENANT_ID) REFERENCES UTILISATEUR (ID),
  CONSTRAINT CK_ENT_TYPE   CHECK (TYPE_ENTRETIEN IN ('RH','TECHNIQUE','FINAL')),
  CONSTRAINT CK_ENT_STATUT CHECK (STATUT_ENTRETIEN IN ('PLANIFIE','REALISE','ANNULE','REPORTE'))
);

CREATE TABLE EVALUATION_CANDIDAT (
  ID              NUMBER(10)      NOT NULL,
  ENTRETIEN_ID    NUMBER(10)      NOT NULL,
  NOTE_TECHNIQUE  NUMBER(4,2),
  COMMENTAIRES    VARCHAR2(4000),
  DECISION        VARCHAR2(12)    NOT NULL,
  CONSTRAINT PK_EVALUATION_CANDIDAT PRIMARY KEY (ID),
  CONSTRAINT UK_EVAL_ENTRETIEN UNIQUE (ENTRETIEN_ID),
  CONSTRAINT FK_EVAL_ENT FOREIGN KEY (ENTRETIEN_ID) REFERENCES ENTRETIEN (ID),
  CONSTRAINT CK_EVAL_NOTE CHECK (NOTE_TECHNIQUE IS NULL OR NOTE_TECHNIQUE BETWEEN 0 AND 20),
  CONSTRAINT CK_EVAL_DEC  CHECK (DECISION IN ('FAVORABLE','DEFAVORABLE','RESERVE'))
);

CREATE TABLE EVALUATION_CRITERE (
  ID             NUMBER(10)     NOT NULL,
  EVALUATION_ID  NUMBER(10)     NOT NULL,
  CRITERE        VARCHAR2(150)  NOT NULL,
  NOTE           NUMBER(4,2)    NOT NULL,
  POIDS          NUMBER(3)      DEFAULT 1 NOT NULL,
  COMMENTAIRE    VARCHAR2(500),
  CONSTRAINT PK_EVALUATION_CRITERE PRIMARY KEY (ID),
  CONSTRAINT UK_CRIT UNIQUE (EVALUATION_ID, CRITERE),
  CONSTRAINT FK_CRIT_EVAL FOREIGN KEY (EVALUATION_ID) REFERENCES EVALUATION_CANDIDAT (ID),
  CONSTRAINT CK_CRIT_NOTE  CHECK (NOTE BETWEEN 0 AND 20),
  CONSTRAINT CK_CRIT_POIDS CHECK (POIDS > 0)
);
