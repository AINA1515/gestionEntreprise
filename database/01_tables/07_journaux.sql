CREATE TABLE LOG_CONNEXION (
  ID               NUMBER(15)     NOT NULL,
  UTILISATEUR_ID   NUMBER(10),
  LOGIN_SAISI      VARCHAR2(100),
  RESULTAT         VARCHAR2(12)   NOT NULL,
  DATE_EVENEMENT   TIMESTAMP(6)   DEFAULT SYSTIMESTAMP NOT NULL,
  ADRESSE_IP       VARCHAR2(45),
  USER_AGENT       VARCHAR2(300),
  CONSTRAINT PK_LOG_CONNEXION PRIMARY KEY (ID),
  CONSTRAINT FK_LOGC_UTIL FOREIGN KEY (UTILISATEUR_ID) REFERENCES UTILISATEUR (ID),
  CONSTRAINT CK_LOGC_RES CHECK (RESULTAT IN ('SUCCES','ECHEC','VERROUILLAGE','DECONNEXION'))
);

CREATE TABLE LOG_ACCES_DOCUMENT (
  ID              NUMBER(15)     NOT NULL,
  DOCUMENT_ID     NUMBER(10)     NOT NULL,
  LOGIN           VARCHAR2(100)  NOT NULL,
  TYPE_ACCES      VARCHAR2(15)   NOT NULL,
  DATE_ACCES      TIMESTAMP(6)   DEFAULT SYSTIMESTAMP NOT NULL,
  ADRESSE_IP      VARCHAR2(45),
  CONSTRAINT PK_LOG_ACCES_DOCUMENT PRIMARY KEY (ID),
  CONSTRAINT FK_LOGD_DOC FOREIGN KEY (DOCUMENT_ID) REFERENCES DOCUMENT (ID),
  CONSTRAINT CK_LOGD_TYPE CHECK (TYPE_ACCES IN
      ('CONSULTATION','TELECHARGEMENT','TELEVERSEMENT','SUPPRESSION','PARTAGE'))
);
