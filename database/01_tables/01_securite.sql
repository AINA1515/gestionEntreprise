PROMPT === 1. Securite ===

-- CANDIDAT est cree ici car il est reference par EMPLOYE et UTILISATEUR.
-- Une personne externe qui postule. Conserve son historique meme apres embauche.
CREATE TABLE CANDIDAT (
  ID                  NUMBER(10)     NOT NULL,
  NOM                 VARCHAR2(100)  NOT NULL,
  PRENOM              VARCHAR2(100)  NOT NULL,
  EMAIL               VARCHAR2(150)  NOT NULL,
  TELEPHONE           VARCHAR2(30),
  ADRESSE             VARCHAR2(300),
  CV_URL              VARCHAR2(500),
  CONSENTEMENT_RGPD   NUMBER(1)      DEFAULT 0 NOT NULL,
  DATE_CONSENTEMENT   DATE,
  DATE_ANONYMISATION  DATE,
  CONSTRAINT PK_CANDIDAT PRIMARY KEY (ID),
  CONSTRAINT CK_CAND_RGPD CHECK (CONSENTEMENT_RGPD IN (0,1))
);
CREATE UNIQUE INDEX UX_CAND_EMAIL ON CANDIDAT (LOWER(EMAIL));

-- Dossier salarie. Cree a la conversion Candidat -> Employe (Bloc 3).
CREATE TABLE EMPLOYE (
  ID                      NUMBER(10)     NOT NULL,
  MATRICULE               VARCHAR2(20)   NOT NULL,
  CANDIDAT_ID             NUMBER(10),
  CIVILITE                VARCHAR2(10),
  NOM                     VARCHAR2(100)  NOT NULL,
  PRENOM                  VARCHAR2(100)  NOT NULL,
  DATE_NAISSANCE          DATE,
  EMAIL_PROFESSIONNEL     VARCHAR2(150),
  TELEPHONE               VARCHAR2(30),
  DATE_EMBAUCHE_INITIALE  DATE           NOT NULL,
  DATE_SORTIE             DATE,
  MOTIF_SORTIE            VARCHAR2(300),
  STATUT_ACTIVITE         VARCHAR2(15)   DEFAULT 'EN_ONBOARDING' NOT NULL,
  CONSTRAINT PK_EMPLOYE PRIMARY KEY (ID),
  CONSTRAINT UK_EMP_MATRICULE UNIQUE (MATRICULE),
  CONSTRAINT UK_EMP_CANDIDAT UNIQUE (CANDIDAT_ID),       -- Candidat 1 --- 0..1 Employe
  CONSTRAINT FK_EMP_CAND FOREIGN KEY (CANDIDAT_ID) REFERENCES CANDIDAT (ID),
  CONSTRAINT CK_EMP_STATUT CHECK (STATUT_ACTIVITE IN ('EN_ONBOARDING','ACTIF','SUSPENDU','SORTI')),
  CONSTRAINT CK_EMP_MATR CHECK (REGEXP_LIKE(MATRICULE, '^EMP-[0-9]{4}-[0-9]{4,}$')),
  CONSTRAINT CK_EMP_DATES CHECK (DATE_SORTIE IS NULL OR DATE_SORTIE >= DATE_EMBAUCHE_INITIALE)
);
CREATE UNIQUE INDEX UX_EMP_EMAIL ON EMPLOYE (LOWER(EMAIL_PROFESSIONNEL));

-- Compte de connexion (interne ou candidat externe).
CREATE TABLE UTILISATEUR (
  ID                       NUMBER(10)     NOT NULL,
  LOGIN                    VARCHAR2(100)  NOT NULL,
  EMAIL                    VARCHAR2(150)  NOT NULL,
  NOM_AFFICHAGE            VARCHAR2(200),
  MOT_DE_PASSE_HASH        VARCHAR2(255),                -- jamais en clair ; NULL si SSO/OAuth2
  TYPE_COMPTE              VARCHAR2(10)   DEFAULT 'INTERNE' NOT NULL,
  EMPLOYE_ID               NUMBER(10),
  CANDIDAT_ID              NUMBER(10),
  STATUT_COMPTE            VARCHAR2(12)   DEFAULT 'ACTIF' NOT NULL,
  NB_ECHECS_CONNEXION      NUMBER(3)      DEFAULT 0 NOT NULL,
  DATE_DERNIERE_CONNEXION  TIMESTAMP(6),
  DATE_EXPIRATION_MDP      DATE,
  CONSTRAINT PK_UTILISATEUR PRIMARY KEY (ID),
  CONSTRAINT FK_UTIL_EMP  FOREIGN KEY (EMPLOYE_ID)  REFERENCES EMPLOYE (ID),
  CONSTRAINT FK_UTIL_CAND FOREIGN KEY (CANDIDAT_ID) REFERENCES CANDIDAT (ID),
  CONSTRAINT CK_UTIL_TYPE   CHECK (TYPE_COMPTE IN ('INTERNE','CANDIDAT')),
  CONSTRAINT CK_UTIL_STATUT CHECK (STATUT_COMPTE IN ('ACTIF','VERROUILLE','DESACTIVE'))
);
CREATE UNIQUE INDEX UX_UTIL_LOGIN ON UTILISATEUR (UPPER(LOGIN));

CREATE TABLE ROLE_RH (
  ID           NUMBER(10)     NOT NULL,
  CODE         VARCHAR2(30)   NOT NULL,
  LIBELLE      VARCHAR2(100)  NOT NULL,
  DESCRIPTION  VARCHAR2(500),
  EST_ACTIF    NUMBER(1)      DEFAULT 1 NOT NULL,
  CONSTRAINT PK_ROLE_RH PRIMARY KEY (ID),
  CONSTRAINT UK_ROLE_CODE UNIQUE (CODE),
  CONSTRAINT CK_ROLE_ACTIF CHECK (EST_ACTIF IN (0,1))
);

CREATE TABLE PERMISSION (
  ID           NUMBER(10)     NOT NULL,
  CODE         VARCHAR2(50)   NOT NULL,
  LIBELLE      VARCHAR2(150)  NOT NULL,
  MODULE       VARCHAR2(20)   NOT NULL,
  CONSTRAINT PK_PERMISSION PRIMARY KEY (ID),
  CONSTRAINT UK_PERM_CODE UNIQUE (CODE)
);

CREATE TABLE ROLE_PERMISSION (
  ID             NUMBER(10) NOT NULL,
  ROLE_ID        NUMBER(10) NOT NULL,
  PERMISSION_ID  NUMBER(10) NOT NULL,
  CONSTRAINT PK_ROLE_PERMISSION PRIMARY KEY (ID),
  CONSTRAINT UK_RP UNIQUE (ROLE_ID, PERMISSION_ID),
  CONSTRAINT FK_RP_ROLE FOREIGN KEY (ROLE_ID)       REFERENCES ROLE_RH (ID),
  CONSTRAINT FK_RP_PERM FOREIGN KEY (PERMISSION_ID) REFERENCES PERMISSION (ID)
);

CREATE TABLE UTILISATEUR_ROLE (
  ID              NUMBER(10)  NOT NULL,
  UTILISATEUR_ID  NUMBER(10)  NOT NULL,
  ROLE_ID         NUMBER(10)  NOT NULL,
  DATE_DEBUT      DATE        DEFAULT SYSDATE NOT NULL,
  DATE_FIN        DATE,
  MOTIF           VARCHAR2(300),
  CONSTRAINT PK_UTILISATEUR_ROLE PRIMARY KEY (ID),
  CONSTRAINT UK_UR UNIQUE (UTILISATEUR_ID, ROLE_ID, DATE_DEBUT),
  CONSTRAINT FK_UR_UTIL FOREIGN KEY (UTILISATEUR_ID) REFERENCES UTILISATEUR (ID),
  CONSTRAINT FK_UR_ROLE FOREIGN KEY (ROLE_ID)        REFERENCES ROLE_RH (ID),
  CONSTRAINT CK_UR_DATES CHECK (DATE_FIN IS NULL OR DATE_FIN >= DATE_DEBUT)
);
